"""Turn docs/privacy.md and docs/data-deletion.md into service/pages.js, the two public pages the PostQueue service
serves at /privacy and /data-deletion (Meta's App Review needs public addresses for both).

The markdown files are the source. Run this after editing them, then deploy the service:

    python tools/make_pages.py
    cd service && wrangler deploy

No dependencies: the pages use a small subset of markdown (headings, paragraphs, bullet lists, bold, code spans,
links and <https://…> autolinks), and that is all this converts."""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = [('PRIVACY', 'privacy.md', '/privacy'), ('DATA_DELETION', 'data-deletion.md', '/data-deletion')]
LINKS = {source: route for _, source, route in PAGES}

STYLE = """
:root { color-scheme: light dark; }
body { font-family: -apple-system, 'Segoe UI', system-ui, sans-serif; line-height: 1.5; margin: 0 auto; padding: 1.5em 1em 3em;
       max-width: 42em; color: #1d1d1f; background: #fff; }
h1 { font-size: 1.7em; margin: 0.4em 0 0.6em; } h2 { font-size: 1.25em; margin: 1.6em 0 0.4em; } h3 { font-size: 1.05em; margin: 1.3em 0 0.3em; }
p, li { margin: 0.5em 0; } code { font-family: Consolas, Menlo, monospace; font-size: 0.93em; background: #f2f2f4; padding: 0.05em 0.3em; border-radius: 4px; }
a { color: #0a5bd3; } nav { font-size: 0.9em; margin-bottom: 1.5em; } nav a { margin-right: 1em; }
@media (prefers-color-scheme: dark) { body { color: #e6e6e8; background: #141416; } code { background: #26262a; } a { color: #7fb3ff; } }
"""

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · PostQueue</title>
<style>{style}</style>
</head>
<body>
<nav><a href="/privacy">Privacy policy</a><a href="/data-deletion">Delete your data</a><a href="https://github.com/DoipSter/PostQueue">PostQueue on GitHub</a></nav>
{body}
</body>
</html>
"""


def inline(text):
    """Escape, then code spans, links, autolinks and bold."""
    text = html.escape(text, quote=False)
    text = re.sub(r'`([^`]+)`', lambda m: f'<code>{m.group(1)}</code>', text)
    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', lambda m: f'<a href="{LINKS.get(m.group(2), m.group(2))}">{m.group(1)}</a>', text)
    text = re.sub(r'&lt;(https?://[^&\s]+)&gt;', r'<a href="\1">\1</a>', text)
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    return text


def convert(markdown):
    """The markdown subset to HTML; returns (title, body)."""
    lines = markdown.replace('\r\n', '\n').split('\n')
    if lines and lines[0] == '---':                      # front matter
        lines = lines[lines.index('---', 1) + 1:]
    title, out, paragraph, items = '', [], [], []

    def flush():
        if paragraph: out.append(f'<p>{inline(" ".join(paragraph))}</p>'); paragraph.clear()
        if items: out.append('<ul>\n' + '\n'.join(f'<li>{inline(i)}</li>' for i in items) + '\n</ul>'); items.clear()

    for line in lines:
        stripped = line.strip()
        if not stripped: flush(); continue
        heading = re.match(r'(#{1,3}) (.+)', stripped)
        if heading:
            flush(); level = len(heading.group(1)); text = inline(heading.group(2))
            if level == 1 and not title: title = heading.group(2)
            out.append(f'<h{level}>{text}</h{level}>'); continue
        if stripped.startswith('- '):
            if paragraph: flush()
            items.append(stripped[2:]); continue
        if items and line.startswith('  '): items[-1] += ' ' + stripped; continue   # wrapped list item
        if items: flush()
        paragraph.append(stripped)
    flush()
    return title, '\n'.join(out)


def main():
    parts = ['// Generated by tools/make_pages.py from docs/privacy.md and docs/data-deletion.md.',
             '// Edit the markdown files and run the script again; do not edit this file.', '']
    for name, source, route in PAGES:
        title, body = convert((ROOT / 'docs' / source).read_text(encoding='utf-8'))
        page = TEMPLATE.format(title=html.escape(title), style=STYLE.strip(), body=body)
        parts.append(f'export const {name} = {json.dumps(page, ensure_ascii=False)};')
        parts.append('')
        print(f'{route}: {title} ({len(page)} bytes)')
    (ROOT / 'service' / 'pages.js').write_text('\n'.join(parts), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
